export function glyphFor(ch: string): number[] {
  const up = ch.toUpperCase();
  if (G[up]) return G[up];
  const plain = up.normalize('NFD').replace(/[̀-ͯ]/g, '');
  if (G[plain]) return G[plain];
  if (ch === '—' || ch === '–') return G['-'];
  if (ch === '’' || ch === '‘') return G["'"];
  if (ch === '“' || ch === '”') return G['"'];
  return G['?'];
}

export function textWidth(text: string, scale = 1): number {
  return text.length ? (text.length * 6 - 1) * scale : 0;
}

export function drawText(g: Ctx, text: string, x: number, y: number, color: string, scale = 1, shadow?: string): void {
  let cx = Math.round(x);
  for (const ch of text) {
    const rows = glyphFor(ch);
    for (let r = 0; r < 7; r++) {
      for (let b = 0; b < 5; b++) {
        if (rows[r] & (1 << (4 - b))) {
          if (shadow) rect(g, cx + b * scale + scale, y + r * scale + scale, scale, scale, shadow);
          rect(g, cx + b * scale, y + r * scale, scale, scale, color);
        }
      }
    }
    cx += 6 * scale;
  }
}

/** Fit text into a width by trimming, adding an ellipsis-like dot run. */
export function fitText(text: string, maxWidth: number, scale = 1): string {
  if (textWidth(text, scale) <= maxWidth) return text;
  let t = text;
  while (t.length > 1 && textWidth(t + '..', scale) > maxWidth) t = t.slice(0, -1);
  return t.trimEnd() + '..';
}
